"use client";

/**
 * Recurring obligations: payroll, rent, utilities and other scheduled bills.
 *
 * No background scheduler runs anywhere in this app — a schedule only
 * creates payables when an owner or analyst explicitly previews and then
 * generates, through the button below. Generated bills are ordinary payables
 * from that point on: this screen does not track them once they exist.
 */

import { useState } from "react";
import { Loader2 } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";

import { companyAction, formatMinor, type CounterpartyRow, type OccurrenceRow, type PayableRow, type RecurringRow } from "./company-api";
import { Check, Field, FormShell, INPUT, useSubmit } from "./company-forms";

const CATEGORIES = [
  { value: "payroll", label: "Payroll" },
  { value: "rent", label: "Rent" },
  { value: "utilities", label: "Utilities" },
  { value: "other", label: "Other" },
] as const;

const WEEKDAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

export function RecurringForm({ counterparties, onSaved }: { counterparties: CounterpartyRow[]; onSaved: () => void }) {
  const suppliers = counterparties.filter((c) => c.isSupplier);
  const [counterpartyId, setParty] = useState("");
  const [category, setCategory] = useState<(typeof CATEGORIES)[number]["value"]>("other");
  const [amount, setAmount] = useState("");
  const [schedule, setSchedule] = useState<"weekly" | "monthly">("monthly");
  const [scheduleDay, setScheduleDay] = useState("1");
  const [startDate, setStartDate] = useState("");
  const [endDate, setEndDate] = useState("");
  const [isPayroll, setIsPayroll] = useState(false);
  const [lockOffset, setLockOffset] = useState("");
  const { busy, error, run } = useSubmit(onSaved);

  if (suppliers.length === 0) return <p className="text-xs text-slate-500 dark:text-slate-400">Add a supplier before scheduling a recurring obligation.</p>;

  return (
    <FormShell
      title="Add a recurring obligation"
      description="Nothing is generated by adding this — it only defines the schedule. Preview and generate it explicitly below, whenever you want its next bills on the ledger."
      error={error}
      busy={busy}
      submitLabel="Add schedule"
      onSubmit={() =>
        run(() =>
          companyAction("add_recurring", {
            counterpartyId,
            category,
            amount,
            schedule,
            scheduleDay: Number(scheduleDay),
            startDate,
            ...(endDate ? { endDate } : {}),
            isPayroll,
            ...(isPayroll && lockOffset ? { payrollLockOffsetDays: Number(lockOffset) } : {}),
          }),
        )
      }
    >
      <Field label="Supplier" required>
        {(id) => (
          <select id={id} className={INPUT} value={counterpartyId} onChange={(e) => setParty(e.target.value)}>
            <option value="">Select a supplier…</option>
            {suppliers.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label="Category" required>
        {(id) => (
          <select id={id} className={INPUT} value={category} onChange={(e) => setCategory(e.target.value as typeof category)}>
            {CATEGORIES.map((c) => (
              <option key={c.value} value={c.value}>
                {c.label}
              </option>
            ))}
          </select>
        )}
      </Field>
      <Field label="Amount, each occurrence" required>
        {(id) => <input id={id} inputMode="decimal" className={INPUT} value={amount} onChange={(e) => setAmount(e.target.value)} />}
      </Field>
      <Field label="Schedule" required>
        {(id) => (
          <select
            id={id}
            className={INPUT}
            value={schedule}
            onChange={(e) => {
              setSchedule(e.target.value as typeof schedule);
              setScheduleDay(e.target.value === "weekly" ? "1" : "1");
            }}
          >
            <option value="monthly">Monthly</option>
            <option value="weekly">Weekly</option>
          </select>
        )}
      </Field>
      <Field
        label={schedule === "weekly" ? "Day of week" : "Day of month"}
        required
        hint={schedule === "monthly" ? "A day past a shorter month's end clamps to that month's last day — never skipped, never rolled into the next month." : undefined}
      >
        {(id) =>
          schedule === "weekly" ? (
            <select id={id} className={INPUT} value={scheduleDay} onChange={(e) => setScheduleDay(e.target.value)}>
              {WEEKDAYS.map((name, i) => (
                <option key={name} value={i}>
                  {name}
                </option>
              ))}
            </select>
          ) : (
            <input id={id} inputMode="numeric" className={INPUT} value={scheduleDay} onChange={(e) => setScheduleDay(e.target.value)} />
          )
        }
      </Field>
      <Field label="Start date" required>
        {(id) => <input id={id} type="date" className={INPUT} value={startDate} onChange={(e) => setStartDate(e.target.value)} />}
      </Field>
      <Field label="End date" hint="Blank means it continues indefinitely.">
        {(id) => <input id={id} type="date" className={INPUT} value={endDate} onChange={(e) => setEndDate(e.target.value)} />}
      </Field>
      <div className="flex flex-col gap-2 pt-1">
        <Check
          label="This is payroll"
          hint="Each generated bill is marked payroll and never deferred past its lock day, the same as one entered by hand."
          checked={isPayroll}
          onChange={setIsPayroll}
        />
        {isPayroll ? (
          <Field label="Bank file locks, days before due" hint="Blank means no lock date is set on generated bills.">
            {(id) => <input id={id} inputMode="numeric" className={INPUT} value={lockOffset} onChange={(e) => setLockOffset(e.target.value)} />}
          </Field>
        ) : null}
      </div>
    </FormShell>
  );
}

function OccurrencePreview({
  recurring,
  payables,
  currency,
  readOnly,
  onChanged,
}: {
  recurring: RecurringRow;
  payables: PayableRow[];
  currency: string;
  readOnly?: boolean;
  onChanged: () => void;
}) {
  const [occurrences, setOccurrences] = useState<OccurrenceRow[] | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [linkingFor, setLinkingFor] = useState<string | null>(null);
  const [success, setSuccess] = useState<string | null>(null);

  const load = async () => {
    setBusy(true);
    setError(null);
    try {
      const response = await companyAction<{ occurrences: OccurrenceRow[] }>("preview_recurring_occurrences", { id: recurring.id });
      setOccurrences(response.occurrences);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : String(cause));
    } finally {
      setBusy(false);
    }
  };

  const generate = async () => {
    setBusy(true);
    setError(null);
    setSuccess(null);
    try {
      await companyAction("generate_recurring_occurrences", { id: recurring.id });
      await load();
      onChanged();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : String(cause));
    } finally {
      setBusy(false);
    }
  };

  const unresolvedCount = occurrences?.filter((o) => !o.resolved).length ?? 0;

  return (
    <div className="col-span-full flex flex-col gap-2 rounded-lg border border-slate-200 bg-slate-50 p-3 dark:border-slate-800 dark:bg-slate-900">
      <div className="flex flex-wrap items-center gap-2">
        <Button type="button" variant="outline" size="sm" disabled={busy} onClick={() => void load()}>
          {busy ? <Loader2 className="size-4 animate-spin" aria-hidden /> : null}
          Preview upcoming occurrences
        </Button>
        {occurrences && unresolvedCount > 0 ? (
          recurring.status === "active" ? (
            <Button type="button" size="sm" disabled={busy} onClick={() => void generate()}>
              Generate {unresolvedCount} bill{unresolvedCount === 1 ? "" : "s"}
            </Button>
          ) : (
            <p className="text-[11px] text-slate-500 dark:text-slate-400">
              This schedule is {recurring.status} — resume it to generate its next bills.
            </p>
          )
        ) : null}
      </div>
      {error ? <p role="alert" className="text-rose-700 dark:text-rose-300">{error}</p> : null}
      {success ? <p role="status" className="text-[11px] leading-relaxed text-emerald-700 dark:text-emerald-400">{success}</p> : null}
      {occurrences ? (
        occurrences.length === 0 ? (
          <p className="text-[11px] text-slate-500 dark:text-slate-400">Nothing falls within the forecast window right now.</p>
        ) : (
          <ul className="flex flex-col gap-1 text-[11px]">
            {occurrences.map((o) => {
              // The resolved occurrence's bill is an ordinary payable in the
              // same workspace sheet, so its details read straight from there.
              const bill = o.payableId ? payables.find((p) => p.id === o.payableId) : undefined;
              return (
                <li key={o.occurrenceId} className="flex flex-wrap items-center gap-2">
                  <span className="tabular-nums">{o.dueDate}</span>
                  {o.resolved ? (
                    <>
                      <Badge variant="outline" className="font-mono text-[10px] text-slate-500">
                        {o.origin === "linked" ? "linked to an existing bill" : "already generated"}
                      </Badge>
                      {bill ? (
                        <span className="min-w-0 text-slate-500 dark:text-slate-400">
                          {bill.counterpartyName} · {bill.externalId || "no reference"} · {formatMinor(bill.amountCents, currency)} · due {bill.dueDate}
                        </span>
                      ) : null}
                    </>
                  ) : (
                    <>
                      <Badge variant="outline" className="font-mono text-[10px]">
                        not yet generated
                      </Badge>
                      {readOnly ? null : (
                        <Button
                          type="button"
                          variant="ghost"
                          size="sm"
                          className="h-7 px-1.5 text-[11px]"
                          aria-expanded={linkingFor === o.occurrenceId}
                          onClick={() => {
                            setSuccess(null);
                            setError(null);
                            setLinkingFor((current) => (current === o.occurrenceId ? null : o.occurrenceId));
                          }}
                        >
                          {linkingFor === o.occurrenceId ? "Cancel link" : "Link an existing bill"}
                        </Button>
                      )}
                      {linkingFor === o.occurrenceId ? (
                        <div className="w-full basis-full">
                          <LinkOccurrenceForm
                            recurring={recurring}
                            occurrence={o}
                            payables={payables}
                            currency={currency}
                            onLinked={(message) => {
                              setLinkingFor(null);
                              void load().then(() => setSuccess(message));
                              onChanged();
                            }}
                            onCancel={() => setLinkingFor(null)}
                          />
                        </div>
                      ) : null}
                    </>
                  )}
                </li>
              );
            })}
          </ul>
        )
      ) : null}
      <p className="text-[11px] text-slate-500 dark:text-slate-400">
        {formatMinor(recurring.amountCents, currency)} · {recurring.schedule}
      </p>
    </div>
  );
}

/**
 * Points one not-yet-generated occurrence at a bill that is already on file
 * instead of generating a duplicate.
 *
 * The list is a picker, not a match: Vantora never merges records on its
 * own, so the person names the exact bill — reference, counterparty, amount,
 * currency and due date shown — and the server re-checks that it belongs to
 * this company. Linking changes only what that schedule date stands for: no
 * second bill is created, no cash moves, and generation skips the date.
 */
function LinkOccurrenceForm({
  recurring,
  occurrence,
  payables,
  currency,
  onLinked,
  onCancel,
}: {
  recurring: RecurringRow;
  occurrence: OccurrenceRow;
  payables: PayableRow[];
  currency: string;
  onLinked: (message: string) => void;
  onCancel: () => void;
}) {
  // Cancelled bills are off the ledger (the forecast skips them), so they
  // are not offered; disputed bills still count, but say so. Ordering is
  // presentational only — it never selects anything by itself.
  const candidates = payables
    .filter((p) => p.status !== "cancelled")
    .sort((a, b) => (a.dueDate === b.dueDate ? a.counterpartyName.localeCompare(b.counterpartyName) : a.dueDate < b.dueDate ? -1 : 1));
  const [payableId, setPayableId] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const selected = payableId ? candidates.find((p) => p.id === payableId) : undefined;

  const link = async () => {
    setBusy(true);
    setError(null);
    try {
      await companyAction("link_recurring_occurrence", {
        id: recurring.id,
        dueDate: occurrence.dueDate,
        payableId,
      });
      onLinked(
        `${occurrence.dueDate} now stands for the existing bill` +
          (selected ? ` (${selected.externalId ? `“${selected.externalId}”, ` : ""}${selected.counterpartyName})` : "") +
          " — the schedule will not generate another bill for that date.",
      );
    } catch (cause) {
      // The server's refusal text (wrong company, already resolved) is
      // written for the person reading it — shown verbatim, as everywhere.
      setError(cause instanceof Error ? cause.message : String(cause));
      setBusy(false);
    }
  };

  if (candidates.length === 0) {
    return (
      <div className="rounded-md border border-dashed border-slate-300 bg-white p-3 text-[11px] leading-relaxed text-slate-500 dark:border-slate-700 dark:bg-slate-950 dark:text-slate-400">
        No eligible bill is on file yet
        {payables.length === 0 ? "" : " — the bills on file are all cancelled, and cancelled bills are off the ledger"}. Enter it under “What you owe”,
        or import it from CSV, then link it here.
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-2 rounded-md border border-slate-200 bg-white p-3 dark:border-slate-800 dark:bg-slate-950">
      <Field
        label={`Link which bill to ${occurrence.dueDate}?`}
        hint="This company's bills are listed with their reference, counterparty, amount and due date — you pick the exact one. Vantora never matches a bill for you."
        required
      >
        {(id) => (
          <select id={id} className={INPUT} value={payableId} onChange={(e) => setPayableId(e.target.value)}>
            <option value="">Select the bill this date stands for…</option>
            {candidates.map((bill) => (
              <option key={bill.id} value={bill.id}>
                {bill.counterpartyName} · {bill.externalId || "no reference"} · {formatMinor(bill.amountCents, currency)}
                {bill.status === "disputed" ? ` (${bill.status})` : ""} · due {bill.dueDate}
              </option>
            ))}
          </select>
        )}
      </Field>
      {selected ? (
        <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 rounded-md bg-slate-50 p-2 text-[11px] dark:bg-slate-900">
          <dt className="text-slate-500 dark:text-slate-400">Counterparty</dt>
          <dd className="font-medium text-slate-900 dark:text-slate-100">{selected.counterpartyName}</dd>
          <dt className="text-slate-500 dark:text-slate-400">Reference</dt>
          <dd className="text-slate-900 dark:text-slate-100">{selected.externalId || "no reference"}</dd>
          <dt className="text-slate-500 dark:text-slate-400">Amount</dt>
          <dd className="tabular-nums text-slate-900 dark:text-slate-100">
            {formatMinor(selected.amountCents, currency)} ({currency})
          </dd>
          <dt className="text-slate-500 dark:text-slate-400">Due date</dt>
          <dd className="tabular-nums text-slate-900 dark:text-slate-100">
            {selected.dueDate}
            {selected.dueDate !== occurrence.dueDate ? (
              <span className="ml-2 text-slate-500 dark:text-slate-400">
                not the same date as this occurrence — linking is your explicit choice, nothing is matched automatically
              </span>
            ) : null}
          </dd>
        </dl>
      ) : null}
      <p className="text-[11px] leading-relaxed text-slate-500 dark:text-slate-400">
        Linking reuses this existing bill for {occurrence.dueDate} — it creates no second bill and moves no cash. The bill stays on the ledger exactly as it is,
        and this schedule will not generate another bill for that date.
      </p>
      {error ? (
        <p role="alert" className="rounded-md border border-rose-300 bg-rose-50 p-2 text-rose-800 dark:border-rose-900 dark:bg-rose-950/40 dark:text-rose-200">
          {error}
        </p>
      ) : null}
      <div className="flex items-center gap-2">
        <Button type="button" size="sm" disabled={busy || !payableId} onClick={() => void link()}>
          {busy ? <Loader2 className="size-4 animate-spin" aria-hidden /> : null}
          Link this bill
        </Button>
        <Button type="button" variant="ghost" size="sm" className="h-7 text-[11px]" disabled={busy} onClick={onCancel}>
          Cancel
        </Button>
      </div>
    </div>
  );
}

export function RecurringList({
  recurring,
  payables,
  currency,
  onChanged,
  readOnly,
}: {
  recurring: RecurringRow[];
  payables?: PayableRow[];
  currency: string;
  onChanged: () => void;
  readOnly?: boolean;
}) {
  const [expanded, setExpanded] = useState<string | null>(null);
  if (recurring.length === 0) {
    return <p className="text-xs text-slate-500 dark:text-slate-400">No recurring obligations set up yet.</p>;
  }
  return (
    <ul className="divide-y divide-slate-100 rounded-xl border border-slate-200 dark:divide-slate-800/60 dark:border-slate-800">
      {recurring.map((row) => (
        <li key={row.id} className="flex flex-wrap items-center gap-2 px-3 py-2 text-xs">
          <span className="min-w-0 flex-1">
            <span className="font-medium text-slate-900 dark:text-slate-100">{row.counterpartyName}</span>
            <span className="ml-2 text-slate-500 dark:text-slate-400">
              {row.schedule === "weekly" ? `every ${WEEKDAYS[row.scheduleDay]}` : `day ${row.scheduleDay} of each month`}
            </span>
          </span>
          <Badge variant="outline" className="font-mono text-[10px]">
            {row.category}
          </Badge>
          {row.status !== "active" ? (
            <Badge variant="outline" className="font-mono text-[10px] text-amber-700 dark:text-amber-400">
              {row.status}
            </Badge>
          ) : null}
          <span className="font-medium tabular-nums">{formatMinor(row.amountCents, currency)}</span>
          <Button type="button" variant="outline" size="sm" onClick={() => setExpanded((cur) => (cur === row.id ? null : row.id))}>
            {expanded === row.id ? "Close" : "Occurrences"}
          </Button>
          {readOnly ? null : row.status === "active" ? (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 px-1.5 text-[11px]"
              onClick={() => void companyAction("set_recurring_status", { id: row.id, status: "paused" }).then(onChanged)}
            >
              Pause
            </Button>
          ) : row.status === "paused" ? (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 px-1.5 text-[11px]"
              onClick={() => void companyAction("set_recurring_status", { id: row.id, status: "active" }).then(onChanged)}
            >
              Resume
            </Button>
          ) : null}
          {readOnly || row.status === "ended" ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 px-1.5 text-[11px] text-rose-700 dark:text-rose-300"
              onClick={() => void companyAction("set_recurring_status", { id: row.id, status: "ended" }).then(onChanged)}
            >
              End
            </Button>
          )}
          {expanded === row.id
            ? <OccurrencePreview recurring={row} payables={payables ?? []} currency={currency} readOnly={readOnly} onChanged={onChanged} />
            : null}
        </li>
      ))}
    </ul>
  );
}
